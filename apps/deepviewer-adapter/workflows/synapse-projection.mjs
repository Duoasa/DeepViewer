import { randomUUID } from 'node:crypto'
import { WorkspaceStore } from './vendor/synapse/index.js'

const MAX_PROJECTION_LENGTH = 8_000
const TRUNCATED_SUFFIX = '\n——…（详情查看全文）'

/** Match the native Chat classifier: injected user-role context is not a prompt. */
export function isHumanUserEvent(event) {
  if (event?.type !== 'user/message') return false
  if (event.surfaceOp !== undefined && event.surfaceOp !== 'append') return false
  const source = event.data?.source
  if (source !== undefined) return source?.kind === 'user'
  // Native logs always identify the source. Restrict compatibility filtering to
  // known complete legacy envelopes so ordinary questions quoting them survive.
  const text = textContent(event.data?.content).trim()
  return !text.startsWith('Current runtime context. This snapshot supersedes earlier runtime-context snapshots.')
    && !/^<system-reminder>[\s\S]*<\/system-reminder>$/i.test(text)
    && !/^\[model changed: assistant turns above this point were generated by [\s\S]+; the session continues with [\s\S]+\]$/i.test(text)
    && !/^The approval policy changed from "(?:ask|never)" to "(?:ask|never)" \(changed by the user\)\.$/.test(text)
}

function textContent(content) {
  if (!Array.isArray(content)) return ''
  return content.filter(block => block?.type === 'text' && typeof block.text === 'string').map(block => block.text).join('\n')
}

/** DeepViewer owns projection semantics; upstream continues to own graph storage. */
export class DeepViewerSynapseStore extends WorkspaceStore {
  async projectSession(session, replayFrom = 0, workspaceTitle = 'DeepViewer 会话') {
    return this.mutate(() => {
      if (this.state.hiddenSessionIds.includes(session.id)) return null
      const cwd = session.header?.meta?.cwd ?? session.header?.cwd
      const workspace = this.dshWorkspace(typeof cwd === 'string' && cwd.trim() ? cwd : '未指定工作目录', workspaceTitle)
      const thread = this.dshThread(workspace, session)
      const previous = new Map(thread.messages.filter(message => Number.isSafeInteger(message.sourceSeq)).map(message => [message.sourceSeq, message]))
      const notes = thread.messages.filter(message => !Number.isSafeInteger(message.sourceSeq))
      // Build 38 projected injections into question cards. Rebuild only the
      // derived messages, retaining thread ids, positions, colors, branch edges,
      // hidden session ids, and any unbound legacy notes. Native logs stay intact.
      thread.messages = []
      thread.pendingProcess = []
      for (const event of session.events) {
        if (event.seq < replayFrom) continue
        this.projectEventInto(workspace, thread, event)
      }
      for (const message of thread.messages) {
        const old = previous.get(message.sourceSeq)
        if (old?.kind === message.kind && typeof old.id === 'string') message.id = old.id
      }
      thread.messages.push(...notes)
      thread.deepviewerProjectionVersion = 1
      return structuredClone(thread)
    }, { deferred: true })
  }

  projectEventInto(workspace, thread, event) {
    if (event.type !== 'user/message') return super.projectEventInto(workspace, thread, event)
    if (!isHumanUserEvent(event) || thread.messages.some(message => message.sourceSeq === event.seq)) return
    const body = textContent(event.data?.content).trim()
    const attachmentOnly = !body && Array.isArray(event.data?.content)
      && event.data.content.some(block => block?.type === 'image' || block?.type === 'file')
    if (!body && !attachmentOnly) return
    // Attachment-only prompts are real turn boundaries. Keep the question card
    // without copying filenames, local paths, or opaque attachment identifiers.
    const text = attachmentOnly ? '附件消息' : body
    const at = new Date(event.time).toISOString()
    const message = {
      id: randomUUID(), kind: 'user', sourceKind: 'user', sourceSeq: event.seq, at,
      ...(attachmentOnly ? { deepviewerAttachmentOnly: true } : {}),
      text: text.length <= MAX_PROJECTION_LENGTH ? text : text.slice(0, MAX_PROJECTION_LENGTH) + TRUNCATED_SUFFIX,
    }
    thread.messages.push(message)
    thread.updatedAt = at
    workspace.updatedAt = at
    if (thread.dshSessionTitle === null) {
      const title = text.replaceAll(/\s+/g, ' ').trim()
      thread.title = title.length > 42 ? title.slice(0, 42) + '...' : title
      thread.dshSessionTitle = thread.title
    }
  }
}
