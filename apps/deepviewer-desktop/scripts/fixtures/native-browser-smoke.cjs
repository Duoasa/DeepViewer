const {app,BrowserWindow,webContents,session}=require('electron')
const {join}=require('node:path')
const {readFileSync,writeFileSync}=require('node:fs')
const restoreOnly=process.argv[3]==='restore'
const {createServer}=require('node:http')
const assert=require('node:assert/strict')
const scratch=process.argv[2]
app.setPath('userData',join(scratch,'userdata'))
const {installSidebarBrowser}=require(join(scratch,'host.cjs'))
let win,server
const wait=ms=>new Promise(r=>setTimeout(r,ms))
async function until(fn){ for(let i=0;i<100;i++){if(await fn())return;await wait(100)}throw Error('condition timeout') }
app.whenReady().then(async()=>{
 server=createServer((req,res)=>{
  if(req.url==='/download'){res.setHeader('Content-Disposition','attachment; filename=smoke.txt');res.end('download ok');return}
  res.setHeader('X-Frame-Options','DENY')
  res.setHeader('Content-Type','text/html')
  res.end(`<title>${req.url}</title><a id="same" href="/second">Next</a><a id="popup" target="_blank" href="/third">New tab</a><input type="file"><input id="draft"><div style="height:3000px"></div>${req.url==='/restore'?'':"<script>localStorage.setItem('saved','yes');document.cookie='browserSmoke=yes; max-age=3600'</script>"}`)
 });await new Promise(r=>server.listen(restoreOnly?Number(readFileSync(join(scratch,'port.txt'),'utf8')):0,'127.0.0.1',r))
 writeFileSync(join(scratch,'port.txt'),String(server.address().port))
 const origin=`http://127.0.0.1:${server.address().port}`
 win=new BrowserWindow({show:false,width:1100,height:900,webPreferences:{preload:join(scratch,'preload.cjs'),webviewTag:true,sandbox:true,contextIsolation:true,nodeIntegration:false}})
 installSidebarBrowser(win,url=>url.startsWith('file:'))
 win.webContents.on('console-message', e=>{if(e.level==='error'||e.level==='warning') console.error('RENDERER',e.message)})
 await win.loadFile(join(scratch,'index.html'))
 if(restoreOnly){
  await win.webContents.executeJavaScript(`window.mountBrowser('restart',${JSON.stringify(origin+'/restore')});void 0`)
  await until(async()=>{const g=webContents.getAllWebContents().find(w=>w.getType()==='webview');return g&&await g.executeJavaScript(`localStorage.getItem('saved')==='yes' && document.cookie.includes('browserSmoke=yes')`).catch(()=>false)})
  console.log('PERSISTENT_BROWSER_RESTART_OK');win.destroy();server.close();app.exit(0);return
 }
 await win.webContents.executeJavaScript(`window.deepviewerDesktop.onBrowserOpen(url=>{window.popupUrl=url;window.mountBrowser('popup',url)});window.removeFirst=window.mountBrowser('first',${JSON.stringify(origin+'/first')});window.mountBrowser('other',${JSON.stringify(origin+'/other')});void 0`)
 const guests=()=>webContents.getAllWebContents().filter(w=>w.getType()==='webview')
 await until(()=>guests().length===2&&guests().every(g=>!g.isLoading()&&g.getURL().startsWith(origin)))
 console.log('two guests loaded')
 const first=guests().find(g=>g.getURL().endsWith('/first'))
 assert.equal(await first.executeJavaScript('typeof window.deepviewerDesktop'),'undefined')
 assert.equal(await first.executeJavaScript('typeof require'),'undefined')
 await until(async()=>await first.executeJavaScript(`!!document.querySelector('#same')`).catch(()=>false))
 console.log('initial ready')
 await first.executeJavaScript(`document.querySelector('#same').click()`,true)
 await until(()=>first.getURL().endsWith('/second')&&!first.isLoading())
 console.log('GUEST HISTORY',first.navigationHistory.canGoBack(),await win.webContents.executeJavaScript(`JSON.stringify([...document.querySelectorAll('webview')].map(v=>({url:v.getURL(),back:typeof v.canGoBack==='function'?v.canGoBack():'missing'})))`))
 await until(()=>win.webContents.executeJavaScript(`document.querySelector('button[aria-label="后退"]').disabled === false`))
 console.log('second ready')
 await win.webContents.executeJavaScript(`document.querySelector('button[aria-label="后退"]').click()`)
 await until(()=>first.getURL().endsWith('/first')&&!first.isLoading())
 await until(async()=>await first.executeJavaScript(`!!document.querySelector('#popup')`).catch(()=>false))
 console.log('back ready')
 await first.executeJavaScript(`document.querySelector('#popup').click()`,true)
 await until(()=>guests().some(g=>g.getURL().endsWith('/third')))
 await win.webContents.executeJavaScript(`window.removeFirst();window.mountBrowser('restored',${JSON.stringify(origin+'/restore')});void 0`)
 await until(()=>guests().some(g=>g.getURL().endsWith('/restore')&&!g.isLoading()))
 const restored=guests().find(g=>g.getURL().endsWith('/restore'))
 assert.equal(await restored.executeJavaScript(`localStorage.getItem('saved')`),'yes')
 const browserSession=session.fromPartition('persist:deepviewer-browser')
 assert.equal((await browserSession.cookies.get({url:origin})).some(c=>c.name==='browserSmoke'),true)
 await win.webContents.executeJavaScript(`window.mountGroup(${JSON.stringify([origin+'/kept-first',origin+'/kept-second'])});void 0`)
 await until(()=>guests().some(g=>g.getURL().endsWith('/kept-first')&&!g.isLoading()))
 const kept=guests().find(g=>g.getURL().endsWith('/kept-first'));const keptId=kept.id
 await kept.executeJavaScript(`document.querySelector('#same').click()`,true)
 await until(()=>kept.getURL().endsWith('/second')&&!kept.isLoading())
 await kept.executeJavaScript(`document.querySelector('#draft').value='unsaved draft';window.scrollTo(0,600);window.identity='same-document'`)
 for(const id of ['kept-1','kept-0','kept-1','kept-0']) {
  await win.webContents.executeJavaScript(`window.selectGroup(${JSON.stringify(id)});void 0`)
  await wait(100)
 }
 assert.equal(kept.isDestroyed(),false)
 assert.equal(kept.id,keptId)
 assert.deepEqual(await kept.executeJavaScript(`({draft:document.querySelector('#draft').value,scroll:window.scrollY,identity:window.identity})`),{draft:'unsaved draft',scroll:600,identity:'same-document'})
 assert.equal(kept.navigationHistory.canGoBack(),true)
 await win.webContents.executeJavaScript(`window.closeGroup('kept-0');void 0`)
 await until(()=>kept.isDestroyed())
 console.log('BROWSER_TAB_LIFETIME_OK: same guest, document, draft, scroll, history across switches; close destroys guest')
 const downloaded=new Promise(resolve=>browserSession.once('will-download',(_e,item)=>{item.setSavePath(join(scratch,'smoke.txt'));item.once('done',(_e,state)=>resolve(state))}))
 restored.downloadURL(origin+'/download')
 assert.equal(await downloaded,'completed')
 assert.equal(readFileSync(join(scratch,'smoke.txt'),'utf8'),'download ok')
 browserSession.flushStorageData()
 await browserSession.cookies.flushStore()
 console.log('NATIVE_BROWSER_OK: independent tabs, frame-denying page, in-tab navigation, back, popup tab, storage/cookies, isolated guests')
 win.destroy();server.close();app.exit(0)
}).catch(e=>{console.error(e);win?.destroy();server?.close();app.exit(1)})
